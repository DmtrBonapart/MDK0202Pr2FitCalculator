//экранирование символов HTML — защита от XSS-атак
//XSS — когда злоумышленник вводит <script>alert('взлом')</script>
//и браузер выполняет это как код, а не отображает как текст
function sanitize(str) {
    //словарь замен: опасный символ → безопасная HTML-сущность
    const map = {
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&#x27;',
        '/': '&#x2F;',
    };
    const reg = /[&<>"'/]/ig;
    //заменяю каждый найденный опасный символ на его безопасный аналог
    return str.replace(reg, (el) => map[el]);
}

//экранирование для вставки в HTML-атрибуты
function escapeAttr(str) {
    if (str === null || str === undefined) return '';
    return sanitize(String(str));
}
